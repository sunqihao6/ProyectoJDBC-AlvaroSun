package proyecto.database;

import org.apache.logging.log4j.LogManager;
import org.apache.logging.log4j.Logger;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

/** Crea la base de datos y sus tablas. No inserta registros de ejemplo. */
public final class DatabaseSchemaInitializer {
    private static final Logger logger = LogManager.getLogger(DatabaseSchemaInitializer.class);

    private DatabaseSchemaInitializer() {
    }

    /** Crea el catálogo MySQL si falta y cambia la conexión a ese catálogo. */
    public static void crearBaseDatosMySQL(Connection connection, String databaseName)
            throws SQLException {
        if (databaseName == null || !databaseName.matches("[A-Za-z0-9_]+")) {
            throw new IllegalArgumentException("Nombre de base de datos no válido: " + databaseName);
        }

        // 1. Crear el catálogo sin eliminar uno que ya exista.
        String sql = "CREATE DATABASE IF NOT EXISTS " + databaseName;
        try (Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }

        // 2. Seleccionar el catálogo que recibirá las tablas.
        connection.setCatalog(databaseName);
        logger.info("Catálogo MySQL '{}' listo", databaseName);
    }

    /** Recrea desde cero todas las tablas del proyecto. */
    public static void crearTablas(Connection connection, boolean mysql) throws SQLException {
        String tipoIdGestor = mysql
                ? "BIGINT NOT NULL AUTO_INCREMENT"
                : "BIGINT GENERATED BY DEFAULT AS IDENTITY";
        String descriptionType = mysql ? "TEXT" : "CLOB";

        // PASO 1: borrar las tablas antiguas desde las dependientes hasta las principales.
        eliminarTablasExistentes(connection);

        // PASO 2: crear las tablas principales antes de las que dependen de ellas.
        crearTablaClientes(connection, tipoIdGestor);
        crearTablasProductos(connection, tipoIdGestor, descriptionType);
        crearTablaInventario(connection, tipoIdGestor);
        crearTablaPedidos(connection, tipoIdGestor);

        logger.info("Esquema de Tech Store recreado desde cero");
    }

    /** Elimina las tablas actuales y antiguas del proyecto respetando sus claves foráneas. */
    private static void eliminarTablasExistentes(Connection connection) throws SQLException {
        String[] tablasEnOrdenDeBorrado = {
                // Tablas dependientes de pedidos/productos: se eliminan primero.
                "pago",
                "detalle_pedido",
                "movimientos_stock",
                "inventario",
                "producto_categoria", "cliente_direccion",
                "pedido",
                "categoria",
                "producto",
                "direccion",
                "cliente"
        };

        for (String nombreTabla : tablasEnOrdenDeBorrado) {
            ejecutarSQL(connection, "DROP TABLE IF EXISTS " + nombreTabla);
        }
    }

    private static void crearTablaClientes(Connection connection, String identity)
            throws SQLException {
        ejecutarSQL(connection, """
                CREATE TABLE IF NOT EXISTS cliente (
                    id_cliente %s PRIMARY KEY,
                    nombre VARCHAR(80) NOT NULL,
                    apellidos VARCHAR(120) NOT NULL,
                    email VARCHAR(180) NOT NULL UNIQUE,
                    telefono VARCHAR(30)
                )
                """.formatted(identity));

        ejecutarSQL(connection, """
                CREATE TABLE IF NOT EXISTS direccion (
                    id_direccion %s PRIMARY KEY,
                    calle VARCHAR(180) NOT NULL,
                    ciudad VARCHAR(100) NOT NULL,
                    codigo_postal VARCHAR(15) NOT NULL,
                    pais VARCHAR(80) NOT NULL DEFAULT 'España'
                )
                """.formatted(identity));

        ejecutarSQL(connection, """
                CREATE TABLE IF NOT EXISTS cliente_direccion (
                    id_cliente BIGINT NOT NULL,
                    id_direccion BIGINT NOT NULL,
                    PRIMARY KEY (id_cliente, id_direccion),
                    CONSTRAINT fk_cliente_direccion_cliente FOREIGN KEY (id_cliente)
                        REFERENCES cliente(id_cliente) ON DELETE CASCADE,
                    CONSTRAINT fk_cliente_direccion_direccion FOREIGN KEY (id_direccion)
                        REFERENCES direccion(id_direccion) ON DELETE CASCADE
                )
                """);
    }

    private static void crearTablasProductos(Connection connection, String identity,
                                             String descriptionType) throws SQLException {
        ejecutarSQL(connection, """
                CREATE TABLE IF NOT EXISTS producto (
                    id_producto %s PRIMARY KEY,
                    nombre VARCHAR(160) NOT NULL,
                    precio DECIMAL(10,2) NOT NULL CHECK (precio >= 0),
                    descripcion %s,
                    activo BOOLEAN NOT NULL DEFAULT TRUE
                )
                """.formatted(identity, descriptionType));

        ejecutarSQL(connection, """
                CREATE TABLE IF NOT EXISTS categoria (
                    id_categoria %s PRIMARY KEY,
                    nombre VARCHAR(80) NOT NULL UNIQUE,
                    descripcion VARCHAR(255)
                )
                """.formatted(identity));

        ejecutarSQL(connection, """
                CREATE TABLE IF NOT EXISTS producto_categoria (
                    id_producto BIGINT NOT NULL,
                    id_categoria BIGINT NOT NULL,
                    PRIMARY KEY (id_producto, id_categoria),
                    CONSTRAINT fk_producto_categoria_producto FOREIGN KEY (id_producto)
                        REFERENCES producto(id_producto) ON DELETE CASCADE,
                    CONSTRAINT fk_producto_categoria_categoria FOREIGN KEY (id_categoria)
                        REFERENCES categoria(id_categoria) ON DELETE CASCADE
                )
                """);
    }

    private static void crearTablaInventario(Connection connection, String identity)
            throws SQLException {
        ejecutarSQL(connection, """
                CREATE TABLE IF NOT EXISTS inventario (
                    id_inventario %s PRIMARY KEY,
                    id_producto BIGINT NOT NULL UNIQUE,
                    stock INT NOT NULL DEFAULT 1 CHECK (stock >= 0),
                    stock_minimo INT NOT NULL DEFAULT 3 CHECK (stock_minimo >= 0),
                    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    CONSTRAINT fk_inventario_producto FOREIGN KEY (id_producto)
                        REFERENCES producto(id_producto) ON DELETE RESTRICT
                )
                """.formatted(identity));
    }

    private static void crearTablaPedidos(Connection connection, String identity)
            throws SQLException {

        // Primero se crea el pedido; después, su tabla de líneas con productos.
        ejecutarSQL(connection, """
                CREATE TABLE IF NOT EXISTS pedido (
                    id_pedido %s PRIMARY KEY,
                    id_cliente BIGINT NOT NULL,
                    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    estado VARCHAR(20) NOT NULL
                        CHECK (estado IN ('PENDIENTE','COMPLETADO','CANCELADO')),
                    total DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
                    CONSTRAINT fk_pedido_cliente FOREIGN KEY (id_cliente)
                        REFERENCES cliente(id_cliente) ON DELETE RESTRICT
                )
                """.formatted(identity));

        ejecutarSQL(connection, """
                CREATE TABLE IF NOT EXISTS detalle_pedido (
                    id_detalle %s PRIMARY KEY,
                    id_pedido BIGINT NOT NULL,
                    id_producto BIGINT NOT NULL,
                    cantidadProducto INT NOT NULL CHECK (cantidadProducto > 0),
                    precio_unitario DECIMAL(10,2) NOT NULL CHECK (precio_unitario >= 0),
                    UNIQUE (id_pedido, id_producto),
                    CONSTRAINT fk_detalle_pedido_pedido FOREIGN KEY (id_pedido)
                        REFERENCES pedido(id_pedido) ON DELETE CASCADE,
                    CONSTRAINT fk_detalle_pedido_producto FOREIGN KEY (id_producto)
                        REFERENCES producto(id_producto) ON DELETE RESTRICT
                )
                """.formatted(identity));

        ejecutarSQL(connection, """
                CREATE TABLE IF NOT EXISTS movimientos_stock (
                    id_movimiento %s PRIMARY KEY,
                    id_producto BIGINT NOT NULL,
                    tipo VARCHAR(20) NOT NULL
                        CHECK (tipo IN ('COMPRA','VENTA','DEVOLUCION','AJUSTE')),
                    cantidadCambiada INT,
                    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    CONSTRAINT fk_producto FOREIGN KEY (id_producto)
                        REFERENCES producto(id_producto) ON DELETE RESTRICT
                )
                """.formatted(identity));

        ejecutarSQL(connection, """
                CREATE TABLE IF NOT EXISTS pago (
                    id_pago %s PRIMARY KEY,
                    id_pedido BIGINT NOT NULL UNIQUE,
                    metodo_pago VARCHAR(30) NOT NULL CHECK (metodo_pago IN ('EFECTIVO','TARJETA')),
                    estado VARCHAR(20) NOT NULL
                        CHECK (estado IN ('PENDIENTE','COMPLETADO','ANULADO')),
                    importe DECIMAL(12,2) NOT NULL CHECK (importe >= 0),
                    fecha_pago TIMESTAMP,
                    CONSTRAINT fk_pedido FOREIGN KEY (id_pedido)
                        REFERENCES pedido(id_pedido) ON DELETE CASCADE
                )
                """.formatted(identity));
    }

    /** Ejecuta una sentencia SQL de creación o ajuste del esquema. */
    private static void ejecutarSQL(Connection connection, String sentenciaSQL) throws SQLException {
        try (Statement sentencia = connection.createStatement()) {
            sentencia.execute(sentenciaSQL);
        }
    }

}
