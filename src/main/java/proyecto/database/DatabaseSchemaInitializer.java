package proyecto.database;

import org.apache.logging.log4j.LogManager;
import org.apache.logging.log4j.Logger;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

/** Crea la base de datos y sus tablas. No inserta registros de ejemplo. */
public final class DatabaseSchemaInitializer {
    private static final Logger logger = LogManager.getLogger(DatabaseSchemaInitializer.class);

    private DatabaseSchemaInitializer() {
    }

    /** Crea el catálogo MySQL si falta y cambia la conexión a ese catálogo. */
    public static void createAndSelectMySqlDatabase(Connection connection, String databaseName)
            throws SQLException {
        if (!databaseName.matches("[A-Za-z0-9_]+")) {
            throw new IllegalArgumentException("Nombre de base de datos no válido: " + databaseName);
        }

        // 1. Crear el catálogo sin eliminar uno que ya exista.
        String sql = "CREATE DATABASE IF NOT EXISTS " + databaseName
                + " CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci";
        try (Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }

        // 2. Seleccionar el catálogo que recibirá las tablas.
        connection.setCatalog(databaseName);
        logger.info("Catálogo MySQL '{}' listo", databaseName);
    }

    /** Crea las tablas si no existen; conserva las tablas y filas existentes. */
    public static void createTables(Connection connection, boolean mysql) throws SQLException {
        String tipoIdGestor = mysql
                ? "BIGINT NOT NULL AUTO_INCREMENT"
                : "BIGINT GENERATED BY DEFAULT AS IDENTITY";
        String descriptionType = mysql ? "TEXT" : "CLOB";

        // Las tablas se crean de padres a dependientes para resolver las claves foráneas.
        crearTablaClientes(connection, tipoIdGestor);
        crearTablasProductos(connection, tipoIdGestor, descriptionType);
        createInventoryTable(connection, tipoIdGestor);
        createOrderTables(connection, tipoIdGestor);

        logger.info("Esquema de Tech Store comprobado; las tablas necesarias existen");
    }

    private static void crearTablaClientes(Connection connection, String identity)
            throws SQLException {
        execute(connection, """
                CREATE TABLE IF NOT EXISTS clientes (
                    id_cliente %s PRIMARY KEY,
                    nombre VARCHAR(80) NOT NULL,
                    apellidos VARCHAR(120) NOT NULL,
                    email VARCHAR(180) NOT NULL UNIQUE,
                    telefono VARCHAR(30),
                )
                """.formatted(identity));

        execute(connection, """
                CREATE TABLE IF NOT EXISTS perfil_cliente (
                    id_cliente %s PRIMARY KEY,
                    fecha_nacimiento DATE,
                    tipo_cliente VARCHAR(30) NOT NULL DEFAULT 'PARTICULAR',
                    CONSTRAINT fk_perfil_cliente FOREIGN KEY (id_cliente)
                        REFERENCES clientes(id_cliente) ON DELETE CASCADE
                )
                """.formatted(identity));

        execute(connection, """
                CREATE TABLE IF NOT EXISTS direcciones (
                    id_direccion %s PRIMARY KEY,
                    id_cliente BIGINT NOT NULL,
                    calle VARCHAR(180) NOT NULL,
                    ciudad VARCHAR(100) NOT NULL,
                    codigo_postal VARCHAR(15) NOT NULL,
                    pais VARCHAR(80) NOT NULL DEFAULT 'España',
                    CONSTRAINT fk_direccion_cliente FOREIGN KEY (id_cliente)
                        REFERENCES clientes(id_cliente) ON DELETE CASCADE
                )
                """.formatted(identity));
    }

    private static void crearTablasProductos(Connection connection, String identity,
                                             String descriptionType) throws SQLException {
        execute(connection, """
                CREATE TABLE IF NOT EXISTS productos (
                    id_producto %s PRIMARY KEY,
                    nombre VARCHAR(160) NOT NULL,
                    marca VARCHAR(100) NOT NULL,
                    precio DECIMAL(10,2) NOT NULL CHECK (precio >= 0),
                    descripcion %s,
                    tipo_producto VARCHAR(40) NOT NULL,
                    socket VARCHAR(40),
                    tipo_ram VARCHAR(20),
                    capacidad VARCHAR(40),
                    interfaz VARCHAR(50),
                    activo BOOLEAN NOT NULL DEFAULT TRUE
                )
                """.formatted(identity, descriptionType));

        execute(connection, """
                CREATE TABLE IF NOT EXISTS categorias (
                    id_categoria %s PRIMARY KEY,
                    nombre VARCHAR(80) NOT NULL UNIQUE,
                    descripcion VARCHAR(255)
                )
                """.formatted(identity));

        execute(connection, """
                CREATE TABLE IF NOT EXISTS producto_categoria (
                    id_producto BIGINT NOT NULL,
                    id_categoria BIGINT NOT NULL,
                    PRIMARY KEY (id_producto, id_categoria),
                    CONSTRAINT fk_pc_producto FOREIGN KEY (id_producto)
                        REFERENCES productos(id_producto) ON DELETE CASCADE,
                    CONSTRAINT fk_pc_categoria FOREIGN KEY (id_categoria)
                        REFERENCES categorias(id_categoria) ON DELETE CASCADE
                )
                """);
    }

    private static void createInventoryTable(Connection connection, String identity)
            throws SQLException {
        execute(connection, """
                CREATE TABLE IF NOT EXISTS inventario (
                    id_inventario %s PRIMARY KEY,
                    id_producto BIGINT NOT NULL UNIQUE,
                    stock INT NOT NULL DEFAULT 0 CHECK (stock >= 0),
                    stock_minimo INT NOT NULL DEFAULT 3 CHECK (stock_minimo >= 0),
                    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    CONSTRAINT fk_inventario_producto FOREIGN KEY (id_producto)
                        REFERENCES productos(id_producto) ON DELETE RESTRICT
                )
                """.formatted(identity));
    }

    private static void createOrderTables(Connection connection, String identity)
            throws SQLException {
        execute(connection, """
                CREATE TABLE IF NOT EXISTS pedidos (
                    id_pedido %s PRIMARY KEY,
                    id_cliente BIGINT NOT NULL,
                    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    estado VARCHAR(20) NOT NULL
                        CHECK (estado IN ('PENDIENTE','COMPLETADO','CANCELADO')),
                    total DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
                    CONSTRAINT fk_pedido_cliente FOREIGN KEY (id_cliente)
                        REFERENCES clientes(id_cliente) ON DELETE RESTRICT
                )
                """.formatted(identity));

        execute(connection, """
                CREATE TABLE IF NOT EXISTS detalle_pedido (
                    id_detalle %s PRIMARY KEY,
                    id_pedido BIGINT NOT NULL,
                    id_producto BIGINT NOT NULL,
                    cantidad INT NOT NULL CHECK (cantidad > 0),
                    precio_unitario DECIMAL(10,2) NOT NULL CHECK (precio_unitario >= 0),
                    CONSTRAINT uq_detalle_pedido_producto UNIQUE (id_pedido, id_producto),
                    CONSTRAINT fk_detalle_pedido FOREIGN KEY (id_pedido)
                        REFERENCES pedidos(id_pedido) ON DELETE CASCADE,
                    CONSTRAINT fk_detalle_producto FOREIGN KEY (id_producto)
                        REFERENCES productos(id_producto) ON DELETE RESTRICT
                )
                """.formatted(identity));

        execute(connection, """
                CREATE TABLE IF NOT EXISTS movimientos_stock (
                    id_movimiento %s PRIMARY KEY,
                    id_producto BIGINT NOT NULL,
                    tipo VARCHAR(20) NOT NULL
                        CHECK (tipo IN ('ENTRADA','SALIDA','DEVOLUCION','AJUSTE')),
                    cantidad INT NOT NULL CHECK (cantidad > 0),
                    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    motivo VARCHAR(180) NOT NULL,
                    id_pedido BIGINT,
                    CONSTRAINT fk_movimiento_producto FOREIGN KEY (id_producto)
                        REFERENCES productos(id_producto) ON DELETE RESTRICT,
                    CONSTRAINT fk_movimiento_pedido FOREIGN KEY (id_pedido)
                        REFERENCES pedidos(id_pedido) ON DELETE SET NULL
                )
                """.formatted(identity));

        execute(connection, """
                CREATE TABLE IF NOT EXISTS pagos (
                    id_pago %s PRIMARY KEY,
                    id_pedido BIGINT NOT NULL UNIQUE,
                    metodo_pago VARCHAR(30) NOT NULL,
                    estado VARCHAR(20) NOT NULL
                        CHECK (estado IN ('PENDIENTE','COMPLETADO','ANULADO')),
                    importe DECIMAL(12,2) NOT NULL CHECK (importe >= 0),
                    fecha_pago TIMESTAMP,
                    CONSTRAINT fk_pago_pedido FOREIGN KEY (id_pedido)
                        REFERENCES pedidos(id_pedido) ON DELETE CASCADE
                )
                """.formatted(identity));
    }

    private static void execute(Connection connection, String sql) throws SQLException {
        try (Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }
}
